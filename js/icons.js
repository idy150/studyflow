/** Devine une icône d'après le nom de la matière. */
export function guessIcon(name = '') {
  const n = name.toLowerCase();
  if (/python|java|program|algo|code|web|info|dev/.test(n)) return 'code';
  if (/donn|sql|data|bd\b/.test(n)) return 'database';
  if (/math|analyse|algèbre|algebre|stat|proba/.test(n)) return 'sigma';
  if (/réseau|reseau|network|internet/.test(n)) return 'globe';
  if (/archi|système|systeme|électron|electron/.test(n)) return 'cpu';
  if (/phys/.test(n)) return 'atom';
  if (/chim/.test(n)) return 'flask';
  if (/bio|svt|médec|medec/.test(n)) return 'dna';
  if (/éco|eco|gestion|compta|financ/.test(n)) return 'chart';
  if (/droit|hist|géo|geo/.test(n)) return 'landmark';
  if (/anglais|français|francais|arabe|langue|english/.test(n)) return 'languages';
  return 'book';
}
